#!/usr/bin/env python3
"""Generate an Ansible inventory from ips.txt.

Reads the Smart Toilet host list and emits a usable inventory. OFFICE
entries (192.168.1.x, reachable only on-site) are excluded. A port recorded
for a host is treated as an SSH port-forward and becomes ansible_port --
several sites share one public IP with a different port each.

Usage:
    ./gen_inventory.py                      # YAML to stdout
    ./gen_inventory.py -o inventory.yml
    ./gen_inventory.py --format ini -o inventory.ini
"""

import argparse
import re
import sys
from pathlib import Path

# "121.120.208.137  (SIMCARD - MBSP TC Male - port 3002)"
ENTRY_RE = re.compile(r"^(?P<host>\S+)\s+\((?P<body>.+)\)\s*$")
PORT_RE = re.compile(r"^port\s+(?P<port>\d+)(?P<flags>.*)$", re.IGNORECASE)

EXCLUDE_KINDS = {"OFFICE"}
GROUP_ORDER = ["simcard", "vpn"]
PARENT_GROUP = "smart_toilet"


def slug(text):
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def parse(path):
    entries, problems = [], []
    for lineno, raw in enumerate(path.read_text().splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue

        m = ENTRY_RE.match(line)
        if not m:
            problems.append(f"{path.name}:{lineno}: cannot parse: {line}")
            continue

        fields = [f.strip() for f in m.group("body").split(" - ")]
        if len(fields) < 2:
            problems.append(f"{path.name}:{lineno}: missing type or location: {line}")
            continue

        kind, location = fields[0].upper(), fields[1]
        port, port_enabled = None, True
        if len(fields) > 2:
            pm = PORT_RE.match(fields[2])
            if pm:
                port = int(pm.group("port"))
                port_enabled = "disabled" not in pm.group("flags").lower()
            else:
                problems.append(
                    f"{path.name}:{lineno}: unrecognised trailing field {fields[2]!r}"
                )

        entries.append(
            {
                # Suffix with the kind: a site can appear under both SIMCARD and
                # VPN, and two inventory entries sharing a name would collide.
                "name": f"{slug(location)}_{kind.lower()}",
                "host": m.group("host"),
                "kind": kind,
                "location": location,
                "port": port,
                "port_enabled": port_enabled,
            }
        )

    seen = {}
    for e in entries:
        seen.setdefault(e["name"], []).append(e["host"])
    for name, hosts in seen.items():
        if len(hosts) > 1:
            problems.append(f"duplicate inventory name {name}: {', '.join(hosts)}")

    return entries, problems


def grouped(entries):
    groups = {}
    for e in entries:
        if e["kind"] in EXCLUDE_KINDS:
            continue
        groups.setdefault(e["kind"].lower(), []).append(e)
    return {
        g: groups[g]
        for g in GROUP_ORDER + sorted(set(groups) - set(GROUP_ORDER))
        if g in groups
    }


def host_lines(entry, indent, sep):
    """Emit the var lines for one host. `sep` is ': ' for YAML, '=' for INI."""
    lines = [f"{indent}ansible_host{sep}{entry['host']}"]
    if entry["port"] is not None and entry["port_enabled"]:
        lines.append(f"{indent}ansible_port{sep}{entry['port']}")
    return lines


def render_yaml(groups):
    out = [
        "# Generated by gen_inventory.py from ips.txt -- do not edit by hand.",
        "# OFFICE (192.168.1.x) entries are excluded: on-site LAN only.",
        "# A host's port is an SSH port-forward, so it maps to ansible_port.",
        "---",
        "all:",
        "  children:",
        f"    {PARENT_GROUP}:",
        "      children:",
    ]
    for group, entries in groups.items():
        out += [f"        {group}:", "          hosts:"]
        for e in sorted(entries, key=lambda x: x["name"]):
            out.append(f"            {e['name']}:")
            out += host_lines(e, " " * 14, ": ")
            out.append(f"              site: {e['location']!r}")
            if e["port"] is not None and not e["port_enabled"]:
                out.append(
                    f"              # port {e['port']} forwarding is disabled"
                    " -- no ansible_port set"
                )
    return "\n".join(out) + "\n"


def render_ini(groups):
    out = [
        "# Generated by gen_inventory.py from ips.txt -- do not edit by hand.",
        "# OFFICE (192.168.1.x) entries are excluded: on-site LAN only.",
    ]
    for group, entries in groups.items():
        out += ["", f"[{group}]"]
        for e in sorted(entries, key=lambda x: x["name"]):
            vars_ = " ".join(host_lines(e, "", "="))
            note = ""
            if e["port"] is not None and not e["port_enabled"]:
                note = f"  # port {e['port']} forwarding disabled"
            out.append(f"{e['name']} {vars_}{note}")
    out += ["", f"[{PARENT_GROUP}:children]"] + list(groups)
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("-i", "--input", type=Path, default=Path("ips.txt"))
    ap.add_argument("-o", "--output", type=Path)
    ap.add_argument("--format", choices=("yaml", "ini"), default="yaml")
    args = ap.parse_args()

    entries, problems = parse(args.input)
    for p in problems:
        print(f"warning: {p}", file=sys.stderr)

    groups = grouped(entries)
    text = (render_yaml if args.format == "yaml" else render_ini)(groups)

    if args.output:
        args.output.write_text(text)
    else:
        sys.stdout.write(text)

    kept = sum(len(v) for v in groups.values())
    summary = ", ".join(f"{g}={len(v)}" for g, v in groups.items())
    print(
        f"{len(entries)} parsed, {len(entries) - kept} excluded, {kept} hosts ({summary})",
        file=sys.stderr,
    )
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
